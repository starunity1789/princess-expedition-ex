"""3.2：X 槽位武器加强——射程 +33%、伤害翻倍。

用法：python tools/gen_x_weapons.py <群星安装目录> <MOD 根目录>

武器数值在原版 common/component_templates/weapon_components.csv 与
mutation_weapon_components.csv（生物飞船突变武器）里，按 key 一行。本脚本：
1. 扫原版 component_templates/*.txt，找出 size = extra_large 且有 prerequisites 的武器
   （帝国能造的 X 槽位武器；太空生物、天灾专用的无科技武器不动）
2. 把两份 CSV 整份拷进 MOD，只改这些行的 min_damage / max_damage（×2）与 range（×1.33）

整文件覆盖原版同名 CSV。目前启用的 MOD 里没有别的 CSV；Real Space - Ships in Scaling
也带这两份 CSV（它把所有射程缩到约 1/6），同时启用时只有一份生效。群星更新后重新运行。
"""
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
GAME = Path(sys.argv[1])
MOD = Path(sys.argv[2])
SRC = GAME / "common" / "component_templates"
DST = MOD / "common" / "component_templates"
DAMAGE_MULT = 2.0
RANGE_MULT = 1.33


def template_blocks(text: str):
    for m in re.finditer(r"^weapon_component_template\s*=\s*\{", text, re.M):
        i, depth = m.end(), 1
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        yield text[m.start():i]


x_keys, skipped = set(), set()
for f in sorted(SRC.glob("*.txt")):
    text = re.sub(r"#[^\n]*", "", f.read_text(encoding="utf-8-sig", errors="replace"))
    for b in template_blocks(text):
        key = re.search(r'\bkey\s*=\s*"([^"]+)"', b)
        size = re.search(r"\bsize\s*=\s*(\w+)", b)
        if key and size and size.group(1) == "extra_large":
            (x_keys if "prerequisites" in b else skipped).add(key.group(1))

DST.mkdir(parents=True, exist_ok=True)
changed_total = 0
for name in ("weapon_components.csv", "mutation_weapon_components.csv"):
    raw = (SRC / name).read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    text = raw.decode("utf-8-sig")
    nl = "\r\n" if "\r\n" in text else "\n"
    lines = text.replace("\r\n", "\n").split("\n")
    header = next(l for l in lines if l.startswith("key;")).split(";")
    i_min, i_max, i_rng = header.index("min_damage"), header.index("max_damage"), header.index("range")
    out, changed = [], []
    for line in lines:
        cells = line.split(";")
        if not line.startswith("#") and cells[0] in x_keys and len(cells) > i_rng:
            old = (cells[i_min], cells[i_max], cells[i_rng])
            cells[i_min] = f"{float(cells[i_min]) * DAMAGE_MULT:.2f}"
            cells[i_max] = f"{float(cells[i_max]) * DAMAGE_MULT:.2f}"
            cells[i_rng] = f"{float(cells[i_rng]) * RANGE_MULT:.2f}"
            changed.append(f"{cells[0]}: dmg {old[0]}-{old[1]} -> {cells[i_min]}-{cells[i_max]}, range {old[2]} -> {cells[i_rng]}")
            line = ";".join(cells)
        out.append(line)
    pad = ";" * (len(header) - 1)
    # CSV 注释只用 ASCII，避免游戏的 CSV 解析器出问题
    note = [f"# The Princesses' Expedition EX: overrides vanilla common/component_templates/{name}; generated by tools/gen_x_weapons.py, do not edit{pad}",
            f"# Only change: buildable extra_large (X slot) weapons have damage x{DAMAGE_MULT:g} and range x{RANGE_MULT:g} ({len(changed)} rows){pad}"]
    data = nl.join(note + out)
    (DST / name).write_bytes((b"\xef\xbb\xbf" if bom else b"") + data.encode("utf-8"))
    changed_total += len(changed)
    print(f"== {name}: {len(changed)} 行")
    for c in changed:
        print("  ", c)
print(f"X 槽位武器：可建造 {len(x_keys)} 个（改了 {changed_total} 行），未改的无科技武器 {len(skipped)} 个：{sorted(skipped)}")
